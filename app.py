    # Строка 2
    c1, c2, c3 = st.columns([2, 3, 3])

    with c1:
        st.markdown(f"**{p1_strategy2}**")

    with c2:
        st.caption("Клетка (2,1)")

        a21 = st.number_input(
            f"{player1} (2,1)",
            value=5.0,
            key="a21"
        )

        b21 = st.number_input(
            f"{player2} (2,1)",
            value=0.0,
            key="b21"
        )

        st.success(
            f"({a21:g}, {b21:g})"
        )

    with c3:
        st.caption("Клетка (2,2)")

        a22 = st.number_input(
            f"{player1} (2,2)",
            value=1.0,
            key="a22"
        )

        b22 = st.number_input(
            f"{player2} (2,2)",
            value=1.0,
            key="b22"
        )

        st.success(
            f"({a22:g}, {b22:g})"
        )

    st.divider()

    # ------------------------------
    # Расчёт
    # ------------------------------

    if st.button(
        "🧮 Рассчитать равновесие Нэша",
        use_container_width=True
    ):

        equilibria = []

        # (1,1)
        if a11 >= a21 and b11 >= b12:
            equilibria.append(
                (
                    p1_strategy1,
                    p2_strategy1,
                    a11,
                    b11
                )
            )

        # (1,2)
        if a12 >= a22 and b12 >= b11:
            equilibria.append(
                (
                    p1_strategy1,
                    p2_strategy2,
                    a12,
                    b12
                )
            )

        # (2,1)
        if a21 >= a11 and b21 >= b22:
            equilibria.append(
                (
                    p1_strategy2,
                    p2_strategy1,
                    a21,
                    b21
                )
            )

        # (2,2)
        if a22 >= a12 and b22 >= b21:
            equilibria.append(
                (
                    p1_strategy2,
                    p2_strategy2,
                    a22,
                    b22
                )
            )

        st.subheader("📊 Результат")

        if equilibria:

            st.success(
                f"Найдено чистых равновесий Нэша: "
                f"{len(equilibria)}"
            )

            for eq in equilibria:

                strategy1 = eq[0]
                strategy2 = eq[1]
                payoff1 = eq[2]
                payoff2 = eq[3]

                st.markdown("### 🎯 Равновесие Нэша")

                col1, col2 = st.columns(2)

                with col1:
                    st.metric(
                        player1,
                        strategy1
                    )

                    st.write(
                        f"💰 Выигрыш: **{payoff1:g}**"
                    )

                with col2:
                    st.metric(
                        player2,
                        strategy2
                    )

                    st.write(
                        f"💰 Выигрыш: **{payoff2:g}**"
                    )

                st.info(
                    "Ни одному игроку не выгодно "
                    "односторонне менять свою стратегию."
                )

        else:

            st.warning(
                "Чистого равновесия Нэша нет."
            )

            # --------------------------
            # Смешанное равновесие
            # --------------------------

            denominator_p = (
                b11 - b12 - b21 + b22
            )

            denominator_q = (
                a11 - a12 - a21 + a22
            )

            if (
                denominator_p != 0
                and denominator_q != 0
            ):

                p = (
                    b12 - b22
                ) / denominator_p

                q = (
                    a21 - a22
                ) / denominator_q

                if (
                    0 <= p <= 1
                    and 0 <= q <= 1
                ):

                    st.success(
                        "🎲 Найдено смешанное равновесие Нэша!"
                    )

                    st.write(
                        f"Вероятность стратегии "
                        f"**{p1_strategy1}** "
                        f"для {player1}: "
                        f"**{p:.2%}**"
                    )

                    st.write(
                        f"Вероятность стратегии "
                        f"**{p2_strategy1}** "
                        f"для {player2}: "
                        f"**{q:.2%}**"
                    )

                    expected1 = (
                        p * q * a11
                        + p * (1 - q) * a12
                        + (1 - p) * q * a21
                        + (1 - p) * (1 - q) * a22
                    )

                    expected2 = (
                        p * q * b11
                        + p * (1 - q) * b12
                        + (1 - p) * q * b21
                        + (1 - p) * (1 - q) * b22
                    )

                    st.write(
                        f"Ожидаемый выигрыш "
                        f"{player1}: **{expected1:.2f}**"
                    )

                    st.write(
                        f"Ожидаемый выигрыш "
                        f"{player2}: **{expected2:.2f}**"
                    )

                else:

                    st.warning(
                        "Смешанное равновесие "
                        "с вероятностями от 0 до 1 "
                        "не найдено."
                    )

            else:

                st.warning(
                    "Смешанное равновесие "
                    "для этой матрицы не определяется "
                    "стандартной формулой."
                )


